import {test,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';

test('exact sample creates genuine CAD and illustrated plans offline on one revision',async({page})=>{
  test.setTimeout(480000);
  await page.route('**/*',route=>['127.0.0.1','localhost','[::1]'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
  await page.goto('/');await page.getByRole('button',{name:'New bookcase',exact:true}).click();
  await page.getByLabel('Project name').fill('Beginner guide acceptance '+Date.now());
  for(const [label,value] of [['Outside width','36 in'],['Outside height','36 in'],['Outside depth','12 in'],['Actual main thickness (mm)','18 mm'],['Actual back thickness (mm)','6 mm']])await page.getByLabel(label,{exact:true}).fill(value);
  await page.getByLabel('Fixed shelves',{exact:true}).selectOption('2');
  await page.getByText('Advanced settings',{exact:true}).click();
  await page.getByLabel('Installed recipe',{exact:true}).selectOption('beginner_screws_18_6_36in_bookcase@1.0.0');
  await expect(page.getByTestId('recipe-state')).toContainText('Technical fabrication method complete');
  await page.getByRole('button',{name:'Create design',exact:true}).click();
  await expect(page.getByTestId('asset-loaded')).toHaveText('7 part instances loaded',{timeout:125000});
  const projectId=await page.getByLabel('Saved projects').inputValue();
  const {project}=await (await page.request.get('/api/v1/projects/'+projectId)).json();
  const revisionId=project.latest_successful_revision_id;
  const {revision}=await (await page.request.get('/api/v1/revisions/'+revisionId)).json();
  expect(revision.spec.materials.main.actual_thickness_mm).toBe('18');
  expect(revision.spec.materials.back.actual_thickness_mm).toBe('6');
  await page.getByRole('button',{name:'Get plans · revision 1',exact:true}).click();
  const download=page.getByRole('link',{name:'Download plans ZIP · revision 1',exact:true});
  await expect(download).toBeVisible({timeout:250000});
  const guide=page.getByRole('link',{name:'Build guide PDF · revision 1',exact:true});
  await expect(guide).toHaveCount(1);await guide.focus();await expect(guide).toBeFocused();
  await expect(page.getByRole('link',{name:'Measured design PDF · revision 1',exact:true})).toHaveCount(0);
  const {jobs}=await (await page.request.get('/api/v1/revisions/'+revisionId)).json();
  expect(jobs.every((j:{state:string})=>j.state==='succeeded')).toBe(true);
  const pack=jobs.find((j:{kind:string})=>j.kind==='package');
  const {manifest}=await (await page.request.get('/api/v1/revisions/'+revisionId+'/manifest?artifact_set_id='+pack.source_artifact_set_id)).json();
  expect(manifest.construction.status).toBe('complete');
  const repo=fileURLToPath(new URL('../../../',import.meta.url));
  const out=process.env.WOODWORK_BEGINNER_EVIDENCE_ROOT||join(repo,'.verification/beginner-guide-20261019');await mkdir(out,{recursive:true});
  await writeFile(join(out,'accepted-project.zip'),await (await page.request.get((await download.getAttribute('href'))!)).body());
  await writeFile(join(out,'accepted-manifest.json'),JSON.stringify(manifest,null,2));
  await writeFile(join(out,'accepted-revision.json'),JSON.stringify(revision,null,2));
  const checked=execFileSync(join(repo,'.venv/Scripts/python.exe'),[join(repo,'diagnostics/verify_beginner_plans.py'),join(out,'accepted-project.zip'),join(out,'accepted-manifest.json')],{encoding:'utf8'});
  await writeFile(join(out,'browser-evidence.json'),JSON.stringify({project_id:projectId,revision_id:revisionId,jobs,inspection:JSON.parse(checked),external_requests_blocked:true},null,2));
  await page.reload();
  await expect(page.getByTestId('asset-loaded')).toHaveText('7 part instances loaded',{timeout:30000});
  await expect(download).toBeVisible({timeout:30000});
  await page.screenshot({path:join(out,'beginner-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});await download.focus();await expect(download).toBeFocused();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:join(out,'beginner-narrow.png'),fullPage:true});
});
