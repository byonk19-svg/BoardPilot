test('canonical dimensions survive display switching, keyboard errors and narrow layouts', async ({page}) => {
  await page.goto('/');
  await expect(page.getByRole('button', {name:'New bookcase', exact:true})).toBeVisible();
  await page.getByRole('button', {name:'New bookcase', exact:true}).click();
  await expect(page.getByLabel('Outside width', {exact:true})).toHaveValue('30 in');
  await page.getByLabel('Display units').selectOption('mm');
  await expect(page.getByTestId('draft-summary')).toContainText('726');
  await page.getByLabel('Display units').selectOption('in');
  await expect(page.getByTestId('draft-summary')).toContainText('726');
  await page.getByLabel('Outside width', {exact:true}).focus();
  await page.keyboard.press('ControlOrMeta+A');
  await page.keyboard.type('1/3 in');
  await expect(page.getByRole('alert')).toContainText('denominator');
  await expect(page.getByLabel('Outside width', {exact:true})).toHaveAttribute('aria-invalid','true');
  await page.setViewportSize({width:390,height:844});
  await page.getByLabel('Outside width', {exact:true}).fill('30 in');
  await expect(page.getByRole('button', {name:'Create design'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:'tests/evidence/m2-narrow-workspace.png',fullPage:true});
});

test('saved draft reopens and cancelling a genuine worker preserves prior downloads', async ({page}) => {
  const projects=await (await page.request.get('/api/v1/projects')).json();
  const project=projects.projects.find((item:{title:string;latest_successful_revision_id:string|null})=>/^Browser bookcase \d+$/.test(item.title)&&item.latest_successful_revision_id);
  expect(project,'This flow uses only the genuine browser acceptance project').toBeTruthy();
  await page.goto('/');
  await page.getByLabel('Saved projects').selectOption(project.id);
  await expect(page.getByTestId('model-revision')).toBeVisible();
  const before=await page.getByTestId('model-revision').innerText();
  const href=await page.getByRole('link',{name:/Download cut list/}).getAttribute('href');
  const csvBefore=await (await page.request.get(href!)).text();
  await page.getByLabel('Outside depth',{exact:true}).fill('14 in');
  await expect(page.getByTestId('draft-summary')).toContainText('349.6');
  await expect(page.getByText('Draft saved locally.',{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Outside depth',{exact:true})).toHaveValue('14 in');
  await expect(page.getByTestId('model-revision')).toHaveText(before);
  await page.getByRole('button',{name:'Revert draft',exact:true}).click();
  const record=await (await page.request.get('/api/v1/revisions/'+project.latest_accepted_revision_id)).json();
  await page.getByRole('button',{name:'Update design',exact:true}).click();
  await expect(page.getByRole('status',{name:'Generation status'})).toContainText(/Generating CAD|Building|Assembling/,{timeout:30_000});
  await page.getByRole('button',{name:'Cancel generation',exact:true}).click();
  await expect(page.getByText('Generation cancelled',{exact:true})).toBeVisible({timeout:10_000});
  await expect(page.getByTestId('model-revision')).toHaveText(before);
  const csvAfter=await (await page.request.get((await page.getByRole('link',{name:/Download cut list/}).getAttribute('href'))!)).text();
  expect(csvAfter).toBe(csvBefore);
  await page.screenshot({path:'tests/evidence/m2-cancel-preserves-model.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole('link',{name:/Download cut list/})).toBeVisible();
  await expect(page.getByTestId('cut-list').getByRole('columnheader',{name:'Finished L × W × T'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:'tests/evidence/m2-narrow-saved-project.png',fullPage:true});
});
